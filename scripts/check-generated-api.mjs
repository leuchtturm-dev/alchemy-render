#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";

const file = await readFile(
  new URL("../src/Api/schema.ts", import.meta.url),
  "utf8",
);
const marker = "\nexport interface paths";
const bodyAt = file.indexOf(marker);
if (bodyAt < 0) {
  throw new Error("generated API declarations marker is missing");
}

const declarations = file.slice(bodyAt + 1);
const expected = file.match(/Declarations SHA-256: ([a-f0-9]{64})/)?.[1];
const source = file.match(/Source SHA-256: ([a-f0-9]{64})/)?.[1];
const actual = createHash("sha256").update(declarations).digest("hex");
if (!expected || expected !== actual) {
  throw new Error(
    `generated API checksum mismatch (expected ${expected ?? "missing"}, actual ${actual}); run pnpm generate:api`,
  );
}
if (!source) {
  throw new Error("generated API source checksum is missing");
}

const expectedHeader = `// @ts-nocheck -- Render's upstream schema contains recursive JSON-pointer aliases
/**
 * Generated by openapi-typescript 7.13.0. Do not edit.
 * Source: https://api-docs.render.com/openapi/render-public-api-1.json
 * Source SHA-256: ${source}
 * Declarations SHA-256: ${expected}
 * Deterministic metadata intentionally omits a timestamp.
 */

`;
const header = file.slice(0, bodyAt + 1);
if (header !== expectedHeader) {
  throw new Error(
    "generated API header or pre-declaration content changed; run pnpm generate:api",
  );
}

console.log(`generated API checksum OK: ${actual}`);
